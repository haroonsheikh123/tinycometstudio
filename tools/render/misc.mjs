/* Privacy, 404, sitemap, RSS, robots, manifest. Pure: (data) → string. */
import { renderLayout } from "./layout.mjs";
import { esc, icon, absUrl, gamePath, newsPath } from "./components.mjs";
import { markdownToHtml, parseFrontMatter } from "./markdown.mjs";

/** Replace {{key}} tokens with settings values (e.g. {{contactEmail}}). */
export function interpolate(text, settings) {
  return String(text).replace(/\{\{\s*([A-Za-z0-9_]+)\s*\}\}/g, (m, k) => (k in settings ? String(settings[k]) : m));
}

/** Generic Markdown page (used for /privacy/). */
export function renderMarkdownPage({ settings: s, source, path, version }) {
  const { data, body } = parseFrontMatter(interpolate(source, s));
  const main = `
<article class="wrap legal">
  <h1>${esc(data.title || "")}</h1>
  ${data.updated ? `<p class="updated">Last updated: ${data.updated.startsWith("[") ? `<mark class="ph">${esc(data.updated)}</mark>` : esc(data.updated)}</p>` : ""}
  <div class="prose prose--article">${markdownToHtml(body)}</div>
</article>`;
  return renderLayout({ settings: s, version, title: `${data.title} · ${s.studioName}`, description: data.description || `${data.title} for ${s.studioName}.`, path, main });
}

export function render404Page({ settings: s, version }) {
  const main = `
<section class="wrap lost">
  <img class="lost__mark float" src="/assets/mark.svg" alt="" width="180" height="180">
  <p class="eyebrow">Error 404</p>
  <h1>This comet drifted off course</h1>
  <p>We couldn't find that page. It may have moved, or it hasn't launched yet.</p>
  <div class="hero-ctas lost__ctas">
    <a class="btn btn--primary" href="/">${icon("back")}<span>Back to home</span></a>
    <a class="btn btn--ghost" href="/#games">See our games</a>
  </div>
</section>`;
  return renderLayout({ settings: s, version, title: `Page not found · ${s.studioName}`, description: "This page drifted off course.", path: "/404", main, noindex: true });
}

export function renderSitemap({ settings: s, games, posts }) {
  const today = new Date().toISOString().slice(0, 10);
  const urls = [
    ["/", today, "1.0"],
    ["/news/", posts[0]?.date || today, "0.8"],
    ["/press/", today, "0.5"],
    ["/privacy/", today, "0.3"],
    ...games.map((g) => [gamePath(g), today, "0.9"]),
    ...posts.map((p) => [newsPath(p), p.updated || p.date, "0.7"])
  ];
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- GENERATED by tools/build.mjs from content/ — do not edit by hand. Domain comes from content/settings.json → siteUrl. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map(([p, d, pr]) => `  <url><loc>${esc(absUrl(s, p))}</loc><lastmod>${esc(String(d).slice(0, 10))}</lastmod><priority>${pr}</priority></url>`).join("\n")}
</urlset>
`;
}

const rfc822 = (d) => new Date(String(d).length === 10 ? d + "T12:00:00Z" : d).toUTCString();
export function renderRss({ settings: s, posts }) {
  const cdata = (x) => `<![CDATA[${String(x).replace(/]]>/g, "]]]]><![CDATA[>")}]]>`;
  return `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
<channel>
  <title>${esc(s.studioName)} News</title>
  <link>${esc(absUrl(s, "/news/"))}</link>
  <atom:link href="${esc(absUrl(s, "/news/feed.xml"))}" rel="self" type="application/rss+xml"/>
  <description>${esc(`News, devlogs and release notes from ${s.studioName}.`)}</description>
  <language>en</language>
  ${posts[0] ? `<lastBuildDate>${rfc822(posts[0].date)}</lastBuildDate>` : ""}
${posts.slice(0, 30).map((p) => `  <item>
    <title>${esc(p.title)}</title>
    <link>${esc(absUrl(s, newsPath(p)))}</link>
    <guid isPermaLink="true">${esc(absUrl(s, newsPath(p)))}</guid>
    <pubDate>${rfc822(p.date)}</pubDate>
    <category>${esc(p.category)}</category>
    <description>${cdata(p.excerpt)}</description>
  </item>`).join("\n")}
</channel>
</rss>
`;
}

export function renderRobots({ settings: s }) {
  return `# GENERATED by tools/build.mjs
User-agent: *
Allow: /
Disallow: /admin/
Disallow: /api/

Sitemap: ${absUrl(s, "/sitemap.xml")}
`;
}

export function renderManifest({ settings: s }) {
  return JSON.stringify({
    name: s.studioName,
    short_name: s.shortName || s.studioName,
    description: s.description,
    start_url: "/",
    scope: "/",
    display: "standalone",
    background_color: "#17183F",
    theme_color: "#17183F",
    icons: [
      { src: "/assets/icon-192.png", sizes: "192x192", type: "image/png" },
      { src: "/assets/icon-512.png", sizes: "512x512", type: "image/png" },
      { src: "/assets/icon.svg", sizes: "any", type: "image/svg+xml" }
    ]
  }, null, 2) + "\n";
}
